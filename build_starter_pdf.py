class SchemePage(Flowable):
    """Full-width visual scheme: UVP + 3 pillars + future ideas."""

    def __init__(self, width):
        super().__init__()
        self.width = width
        self.height = 168 * mm

    def draw(self):
        c = self.canv
        w, h = self.width, self.height

        def box(x, y, bw, bh, fill, title, body, title_size=8.5, body_size=7):
            c.setFillColor(fill)
            c.roundRect(x, y, bw, bh, 5, fill=1, stroke=0)
            c.setFillColor(white)
            c.setFont("DejaVuB", title_size)
            c.drawString(x + 8, y + bh - 16, title)
            c.setFont("DejaVu", body_size)
            textobject = c.beginText(x + 8, y + bh - 30)
            textobject.setFillColor(white)
            textobject.setFont("DejaVu", body_size)
            textobject.setLeading(10)
            for line in body:
                textobject.textLine(line)
            c.drawText(textobject)

        def arrow(x1, y1, x2, y2):
            c.setStrokeColor(NAVY)
            c.setFillColor(NAVY)
            c.setLineWidth(1.2)
            c.line(x1, y1, x2, y2)
            c.drawCentredString((x1 + x2) / 2, (y1 + y2) / 2 + 3, "")

        # UVP banner
        c.setFillColor(NAVY)
        c.roundRect(0, h - 38 * mm, w, 36 * mm, 6, fill=1, stroke=0)
        c.setFillColor(white)
        c.setFont("DejaVuB", 9)
        c.drawString(10, h - 12 * mm, "Уникальное ценностное предложение")
        c.setFont("DejaVu", 8)
        uvp = (
            "За N времени после загрузки справочника в Starter — автоматическое обогащение"
            " за несколько кликов: качественные габариты и фото для выкладки,"
        )
        c.drawString(10, h - 20 * mm, uvp)
        c.drawString(
            10,
            h - 28 * mm,
            "и дальше — SpacePlanner у того же подрядчика. Не недели ручного поиска и внесения в справочник.",
        )

        # flow
        fy = h - 58 * mm
        steps = [
            (0, "1. Выгрузка\nсправочника"),
            (1, "2. Несколько\nкликов — запуск\nобогащения"),
            (2, "3. Автомат.\nобогащение\nза N времени"),
            (3, "4. ВГХ было / стало\n+ утверждение"),
            (4, "5. SpacePlanner\nвыкладка"),
        ]
        sw = (w - 8) / 5
        for i, (_, t) in enumerate(steps):
            x = i * sw
            c.setFillColor(HexColor("#E8E4DC") if i < 4 else HexColor("#D5E0D8"))
            c.setStrokeColor(LINE)
            c.setLineWidth(0.6)
            c.roundRect(x, fy, sw - 6, 22 * mm, 4, fill=1, stroke=1)
            c.setFillColor(INK)
            c.setFont("DejaVu", 7)
            textobject = c.beginText(x + 5, fy + 15 * mm)
            textobject.setLeading(9)
            for line in t.split("\n"):
                textobject.textLine(line)
            c.drawText(textobject)
            if i < 4:
                c.setFillColor(NAVY)
                c.setFont("DejaVuB", 9)
                c.drawString(x + sw - 7, fy + 9 * mm, ">")

        # 3 pillars
        py = fy - 48 * mm
        ph = 42 * mm
        pw = (w - 12) / 3
        pillars = [
            (
                PILLAR1,
                "Опора 1. Срок",
                [
                    "Через какое время после",
                    "загрузки справочника в Starter",
                    "будет результат.",
                    "Не «сколько тысяч SKU»,",
                    "а N времени автообогащения.",
                ],
            ),
            (
                PILLAR2,
                "Опора 2. Единое окно",
                [
                    "Один подрядчик:",
                    "справочник подтянуть",
                    "и планограммы в SP.",
                    "Один договор,",
                    "одна интеграция.",
                ],
            ),
            (
                PILLAR3,
                "Опора 3. Было / стало",
                [
                    "Сравнение ВГХ было и стало",
                    "(и фото). Нули и прочерки",
                    "тоже видны. Можно принять",
                    "работу и отловить брак",
                    "до выкладки.",
                ],
            ),
        ]
        for i, (col, title, body) in enumerate(pillars):
            box(i * (pw + 6), py, pw, ph, col, title, body)

        c.setFillColor(INK)
        c.setFont("DejaVuB", 8)
        c.drawString(0, py - 8 * mm, "Идеи на потом  ·  в Starter пока нельзя обещать")

        iy = 4 * mm
        ih = 28 * mm
        iw = (w - 12) / 3
        futures = [
            (
                FUT,
                "Кладбищенская аналитика",
                [
                    "Товар вышел из линейки,",
                    "не продаётся, но строка",
                    "в справочнике осталась",
                    "и путает анализ продаж.",
                ],
            ),
            (
                HexColor("#5A6B7A"),
                "Дубли внутри файла",
                [
                    "Разные коды, похожие имена.",
                    "Повторная заливка того же",
                    "списка уже не плодит копии.",
                    "Поиск всех дублей — позже.",
                ],
            ),
            (
                HexColor("#6A5850"),
                "Маркетплейсы / селлеры",
                [
                    "Кабинеты WB/Ozon, витрины,",
                    "цены и остатки на площадках.",
                    "Другой клиент и продукт,",
                    "не Starter для сети.",
                ],
            ),
        ]
        for i, (col, title, body) in enumerate(futures):
            box(i * (iw + 6), iy, iw, ih, col, title, body, 7.5, 6.2)


def header_footer(canvas, doc):
    canvas.saveState()
    canvas.setFillColor(NAVY)
    canvas.rect(0, H - 12 * mm, W, 12 * mm, fill=1, stroke=0)
    canvas.setFillColor(white)
    canvas.setFont("DejaVu", 8)
    canvas.drawString(18 * mm, H - 8 * mm, "Автокарточки Starter  ·  позиционирование, УЦП, скрипты ОП")
    canvas.setFillColor(NAVY)
    canvas.rect(0, 0, W, 10 * mm, fill=1, stroke=0)
    canvas.setFillColor(white)
    canvas.setFont("DejaVu", 8)
    canvas.drawRightString(W - 18 * mm, 4 * mm, f"{doc.page}")
    canvas.restoreState()


