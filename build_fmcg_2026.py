# Regional mid-size names: regional_2026.REGIONAL_SECTIONS (same 10 columns as HEADER).

def font_like(src, **kw):
    return Font(
        name=kw.get("name", src.name or "Times New Roman"),
        size=kw.get("size", src.size or 11),
        bold=kw.get("bold", src.bold),
        italic=src.italic,
        color=src.color,
        underline=src.underline,
    )


def clone_style(src, dst):
    dst.font = copy(src.font)
    dst.fill = copy(src.fill)
    dst.alignment = copy(src.alignment)
    dst.border = copy(src.border)
    dst.number_format = src.number_format
    dst.protection = copy(src.protection)


HEADER_FONT = Font(name="Times New Roman", size=11, bold=True)
HEADER_FILL = PatternFill("solid", fgColor=TEAL)
WRAP_TOP = Alignment(wrap_text=True, vertical="top", horizontal="left")


def restyle_header_row(ws):
    proto = ws.cell(1, 8)
    for col in range(1, 11):
        c = ws.cell(1, col)
        if col > 8:
            clone_style(proto, c)
        c.value = HEADER[col - 1]
        c.font = HEADER_FONT
        c.fill = HEADER_FILL
        c.alignment = WRAP_TOP


def ensure_extra_cols(ws, r):
    proto = ws.cell(r, 8)
    for col in (9, 10):
        clone_style(proto, ws.cell(r, col))


def fill_row(ws, r, name, data):
    fact, period, yoy, fy, stores, note = data
    ensure_extra_cols(ws, r)
    ws.cell(r, 3).value = fact
    ws.cell(r, 4).value = period
    ws.cell(r, 5).value = yoy
