    c.set_categories(cats)
    c.legend = None
    c.style = 10
    c.y_axis.scaling.orientation = "maxMin"
    c.dataLabels = DataLabelList()
    c.dataLabels.showVal = True
    c.dataLabels.showCatName = False
    c.dataLabels.showSerName = False
