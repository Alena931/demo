    c.x_axis.title = x_title
    c.y_axis.title = None
    data = Reference(ws, min_col=val_col, min_row=header_row, max_row=last_row)
    cats = Reference(ws, min_col=cat_col, min_row=header_row + 1, max_row=last_row)
