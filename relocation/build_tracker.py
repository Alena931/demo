THIN = Side(border_style="thin", color="BFBFBF")
BORDER = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)
HEADER_FILL = PatternFill("solid", fgColor="305496")
HEADER_FONT = Font(bold=True, color="FFFFFF")
WRAP = Alignment(wrap_text=True, vertical="top")


def style_header(ws, ncols):
    for col in range(1, ncols + 1):
        c = ws.cell(row=1, column=col)
        c.fill = HEADER_FILL
        c.font = HEADER_FONT
        c.alignment = Alignment(wrap_text=True, vertical="center", horizontal="center")
        c.border = BORDER
    ws.row_dimensions[1].height = 32
    ws.freeze_panes = "A2"


def add_validation(ws, col_letter, values, last_row, name):
    formula = '"' + ",".join(values) + '"'
    dv = DataValidation(type="list", formula1=formula, allow_blank=True,
                        showDropDown=False)
    dv.error = "Выберите значение из списка"
    dv.errorTitle = "Недопустимое значение"
    dv.prompt = "Выберите из списка"
    dv.promptTitle = name
    ws.add_data_validation(dv)
    dv.add(f"{col_letter}2:{col_letter}{last_row}")


def add_priority_conditional(ws, col_letter, last_row):
    rng = f"{col_letter}2:{col_letter}{last_row}"
    for prio, fill in PRIORITY_FILL.items():
        font = Font(bold=True, color="FFFFFF") if prio in PRIORITY_FONT_WHITE else Font(bold=True)
        rule = FormulaRule(formula=[f'${col_letter}2="{prio}"'], fill=fill, font=font)
        ws.conditional_formatting.add(rng, rule)


def add_status_conditional(ws, col_letter, last_row):
    rng = f"{col_letter}2:{col_letter}{last_row}"
    for status, fill in STATUS_FILL.items():
        rule = FormulaRule(formula=[f'${col_letter}2="{status}"'], fill=fill)
        ws.conditional_formatting.add(rng, rule)


